import { useEffect, useState } from 'react';
import { pocketbaseClient as pb } from '@/lib/pocketbase-client';
import type { AdminNotification } from '@/lib/admin';

export function Settings() {
  const [notifications, setNotifications] = useState<AdminNotification[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState('');
  const [notice, setNotice] = useState('');
  const [revision, setRevision] = useState(0);

  useEffect(() => {
    let active = true;
    setLoading(true);
    pb.collection('ghost_notifications').getFullList<AdminNotification>({ sort: '-created', expand: 'owner', requestKey: null })
      .then((rows) => { if (active) { setNotifications(rows); setError(''); } })
      .catch(() => { if (active) setError('Could not load notifications.'); })
      .finally(() => { if (active) setLoading(false); });
    return () => { active = false; };
  }, [revision]);

  async function remove(id: string) {
    setBusy(id); setError(''); setNotice('');
    try {
      await pb.collection('ghost_notifications').delete(id);
      setNotice('Notification removed.');
      setRevision((v) => v + 1);
    } catch { setError('Could not remove the notification.'); }
    finally { setBusy(''); }
  }

  if (loading) return <div className="loading-state"><div className="loading-bar" />Loading settings…</div>;

  return (
    <div className="admin-section">
      {error && <div className="status-message error-message" role="alert">{error}</div>}
      {notice && <div className="status-message" role="status">{notice}</div>}
      <section className="dashboard-panel">
        <h2>Site data</h2>
        <p className="muted-note">The Laughing Ghost Network stores all member, profile, contribution, review, report, notification, audit, and revision data in PocketBase. Member-owned data can be exported by each member from their own Ghost Space. There is no separate site-wide export here — use the PocketBase admin dashboard for raw backups.</p>
      </section>
      <section className="dashboard-panel">
        <h2>Notifications ({notifications.length})</h2>
        <p className="muted-note">Private member notifications generated by network events. Remove stale or erroneous entries.</p>
        {!notifications.length ? <p className="muted-note">No notifications.</p> : (
          <div className="admin-list">
            {notifications.map((n) => (
              <article className="dashboard-item" key={n.id}>
                <div className="admin-work-head">
                  <span className="validation-badge">{n.type}</span>
                  {!n.read && <span className="validation-badge validation-tested">Unread</span>}
                </div>
                <h3>{n.title}</h3>
                <p>{n.body}</p>
                <p className="muted-note">To {n.expand?.owner?.email || 'member'}</p>
                <div className="item-actions">
                  <button disabled={busy === n.id} onClick={() => remove(n.id)}>Remove</button>
                </div>
              </article>
            ))}
          </div>
        )}
      </section>
    </div>
  );
}
