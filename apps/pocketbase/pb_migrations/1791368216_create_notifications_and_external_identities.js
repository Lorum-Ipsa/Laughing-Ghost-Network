/// <reference path="../pb_data/types.d.ts" />

// Completes the backend data model for the Laughing Ghost Network.
//
// The existing collections already cover Ghost profiles, contributions
// (ghost_work, including project + Table Talks kinds), project memberships
// (ghost_participations), applications, reports, and translations. Account
// email stays on the private `users` auth collection (list/view = self only);
// public ghost_profiles carry no email and expose only what a Ghost chooses
// to publish.
//
// This migration adds the two remaining collections:
//
//   1. ghost_external_identities — structured, per-platform verified
//      identities for a Ghost profile (replacing the free-text external_links
//      blob as the canonical backend source). Public read; owner-managed.
//      Backfilled from existing external_links so seeded example profiles and
//      any member profile already carry structured identities.
//
//   2. ghost_notifications — private, per-member notifications generated by
//      server-side hooks (contribution published/rejected, participation
//      received, application accepted/declined, welcome). Owner-only read;
//      create is system-only (hooks/superuser).
//
// Additive only — no existing field or rule is changed.

migrate((app) => {
  const users = app.findCollectionByNameOrId('users');
  const profiles = app.findCollectionByNameOrId('ghost_profiles');
  const work = app.findCollectionByNameOrId('ghost_work');

  // --- 1. External identities ---
  let identities;
  try {
    identities = app.findCollectionByNameOrId('ghost_external_identities');
  } catch (_) {
    identities = new Collection({
      name: 'ghost_external_identities',
      type: 'base',
      // Public read: a Ghost chooses to publish these. Writes are owner-scoped
      // so members can manage identities directly in a future UI; the sync
      // hook also writes them (as superuser, bypassing rules) from
      // external_links until the frontend adopts the collection.
      listRule: '',
      viewRule: '',
      createRule: "@request.auth.id != '' && owner = @request.auth.id",
      updateRule: "@request.auth.id != '' && owner = @request.auth.id",
      deleteRule: "@request.auth.id != '' && owner = @request.auth.id",
      fields: [
        { name: 'owner', type: 'relation', collectionId: users.id, maxSelect: 1, cascadeDelete: true },
        { name: 'profile', type: 'relation', collectionId: profiles.id, required: true, maxSelect: 1, cascadeDelete: true },
        { name: 'platform', type: 'text', required: true, max: 100 },
        { name: 'url', type: 'url', required: true },
        { name: 'handle', type: 'text', max: 100 },
        { name: 'verified', type: 'bool' },
        { name: 'sort', type: 'number' },
        { name: 'created', type: 'autodate', onCreate: true },
        { name: 'updated', type: 'autodate', onCreate: true, onUpdate: true },
      ],
    });
    app.save(identities);
  }

  // --- 2. Notifications ---
  let notifications;
  try {
    notifications = app.findCollectionByNameOrId('ghost_notifications');
  } catch (_) {
    notifications = new Collection({
      name: 'ghost_notifications',
      type: 'base',
      // Owner-only read/update/delete. createRule is null: notifications are
      // produced server-side by hooks (superuser), never by a client POST.
      listRule: "@request.auth.id != '' && owner = @request.auth.id",
      viewRule: "@request.auth.id != '' && owner = @request.auth.id",
      createRule: null,
      updateRule: "@request.auth.id != '' && owner = @request.auth.id",
      deleteRule: "@request.auth.id != '' && owner = @request.auth.id",
      fields: [
        { name: 'owner', type: 'relation', collectionId: users.id, required: true, maxSelect: 1, cascadeDelete: true },
        {
          name: 'type',
          type: 'select',
          required: true,
          maxSelect: 1,
          values: [
            'welcome',
            'work_published',
            'work_rejected',
            'participation_received',
            'application_accepted',
            'application_declined',
            'report_received',
          ],
        },
        { name: 'title', type: 'text', required: true, max: 200 },
        { name: 'body', type: 'text', max: 1000 },
        { name: 'link', type: 'text', max: 500 },
        { name: 'read', type: 'bool' },
        { name: 'related_work', type: 'relation', collectionId: work.id, maxSelect: 1 },
        { name: 'created', type: 'autodate', onCreate: true },
        { name: 'updated', type: 'autodate', onCreate: true, onUpdate: true },
      ],
    });
    app.save(notifications);
  }

  // --- 3. Backfill external identities from existing external_links ---
  // Parses each profile's `external_links` ("Platform: url" per line) into
  // structured ghost_external_identities rows. Idempotent: skips a pair that
  // already exists for the profile + url.
  const allProfiles = app.findAllRecords('ghost_profiles');
  for (const profile of allProfiles) {
    const raw = profile.getString('external_links') || '';
    const owner = profile.getString('owner');
    const profileId = profile.id;
    let sort = 0;
    for (const line of raw.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      const idx = trimmed.indexOf(':');
      if (idx === -1) continue;
      const platform = trimmed.slice(0, idx).trim();
      const url = trimmed.slice(idx + 1).trim();
      if (!platform || !url) continue;
      sort += 10;
      let existing = [];
      try {
        existing = app.findRecordsByFilter(
          'ghost_external_identities',
          'profile = {:pid} && url = {:url}',
          '',
          1,
          0,
          { pid: profileId, url },
        );
      } catch (_) { /* collection just created — treat as empty */ }
      if (existing.length > 0) continue;
      const rec = new Record(identities);
      rec.set('owner', owner);
      rec.set('profile', profileId);
      rec.set('platform', platform);
      rec.set('url', url);
      rec.set('sort', sort);
      app.save(rec);
    }
  }
}, (app) => {
  for (const name of ['ghost_notifications', 'ghost_external_identities']) {
    try { app.delete(app.findCollectionByNameOrId(name)); } catch (_) { /* already absent */ }
  }
});
